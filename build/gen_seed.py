#!/usr/bin/env python3
"""Generate cohort/supabase/seed.sql from the curriculum markdown.

The weekly briefs are the source of truth. Titles, phases, AI licences and every
acceptance criterion come straight out of content/week-*.md, so the dashboard can
never drift from the PDFs students are holding.
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
OUT = pathlib.Path("/Users/iyonsiisrael/cohort/supabase/seed.sql")

CHECK = re.compile(r"^- \[ \] (.+)$")
LICENCE = re.compile(r"\b(red|yellow|green)\b", re.I)


def q(s):
    return "'" + s.replace("'", "''") + "'"


def parse(path):
    raw = path.read_text(encoding="utf-8")
    _, fm, body = raw.split("---", 2)
    meta = {}
    for line in fm.strip().splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()

    # "Red closing, Yellow opens Sunday" -> the licence in force at the start
    m = LICENCE.search(meta.get("license", "yellow"))
    licence = (m.group(1) if m else "yellow").lower()

    criteria = [m.group(1).strip() for m in
                (CHECK.match(l) for l in body.splitlines()) if m]
    return meta, licence, criteria


def main():
    lines = [
        "-- Generated by build/gen_seed.py. Do not edit by hand.",
        "-- Source of truth: fullstack-bootcamp/content/week-*.md",
        "",
        "-- Idempotent on purpose. The previous version opened with",
        "--   truncate criteria, cohort_weeks, weeks restart identity cascade;",
        "-- which cascades through submissions into marks, so re-running this in production",
        "-- to pick up a curriculum edit would have deleted every mark in the system.",
        "-- Upsert instead: safe to run against a live cohort.",
        "",
    ]

    total_criteria = 0
    for path in sorted(CONTENT.glob("week-*.md")):
        meta, licence, criteria = parse(path)
        wk = int(meta["week"])
        pdf = f"Week-{meta['week']}-" + re.sub(
            r"[^a-z0-9]+", "-", meta["title"].lower()).strip("-") + ".pdf"

        lines.append(
            "insert into weeks (week_no, title, phase, licence, standfirst, pdf_path, submittable)"
            " values\n"
            f"  ({wk}, {q(meta['title'])}, {q(meta['phase'])}, {q(licence)}, "
            f"{q(meta['standfirst'])}, {q(pdf)}, {'false' if wk == 0 else 'true'})\n"
            "on conflict (week_no) do update set\n"
            "  title = excluded.title, phase = excluded.phase, licence = excluded.licence,\n"
            "  standfirst = excluded.standfirst, pdf_path = excluded.pdf_path,\n"
            "  submittable = excluded.submittable;"
        )
        if criteria:
            vals = ",\n".join(
                f"  ((select id from weeks where week_no = {wk}), {i}, {q(c)})"
                for i, c in enumerate(criteria, 1)
            )
            lines.append(
                f"delete from criteria where week_id = (select id from weeks where week_no = {wk});")
            lines.append(f"insert into criteria (week_id, position, text) values\n{vals};")
            total_criteria += len(criteria)
        lines.append("")

    # A cohort to develop against, scheduled from a fixed Monday.
    lines += [
        "-- Demo cohort. Week 0 opened 6 weeks ago, so weeks 1 to 7 are live.",
        "insert into cohorts (id, name, enrolment_code, starts_on)",
        "values ('11111111-1111-1111-1111-111111111111', 'Lagos 01', 'LAGOS01', "
        "current_date - interval '6 weeks')",
        "on conflict (id) do nothing;",
        "",
        "insert into cohort_weeks (cohort_id, week_id, opens_on, due_on)",
        "select '11111111-1111-1111-1111-111111111111', w.id,",
        "       (current_date - interval '6 weeks') + (w.week_no * interval '7 days'),",
        "       (current_date - interval '6 weeks') + (w.week_no * interval '7 days')",
        "         + interval '6 days 23 hours'",
        "from weeks w",
        "on conflict (cohort_id, week_id) do nothing;",
    ]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    print(f"  {len(list(CONTENT.glob('week-*.md')))} weeks, {total_criteria} criteria")


if __name__ == "__main__":
    main()
